/// Training dataset result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrainingDataset {
    pub config: DatasetTrainerConfig,
    pub datapoints: Vec<TrainingDatapoint>,
    pub statistics: DatasetStatistics,
    pub quality_report: QualityReport,
}

/// Dataset statistics
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct DatasetStatistics {
    pub total_datapoints: usize,
    pub total_tokens: usize,
    pub avg_quality_score: f32,
    pub category_distribution: HashMap<String, usize>,
    pub source_distribution: HashMap<String, usize>,
    pub deduplication_removed: usize,
    pub processing_time_seconds: f64,
    /// Processors actually used
    pub processors_used: Vec<String>,
}

/// Quality analysis report
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct QualityReport {
    pub total_analyzed: usize,
    pub passed_quality: usize,
    pub failed_quality: usize,
    pub avg_quality: f32,
    pub min_quality: f32,
    pub max_quality: f32,
    pub issues: Vec<QualityIssue>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct QualityIssue {
    pub datapoint_id: String,
    pub issue_type: String,
    pub severity: String, // "warning" | "error"
    pub message: String,
}

