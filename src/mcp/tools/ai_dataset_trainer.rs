/// Dataset item with embeddings ready for training
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrainingDatapoint {
    pub id: String,
    pub text: String,
    pub source: String,
    pub category: String,
    pub metadata: HashMap<String, String>,
    /// Generated by JAX vectorization
    #[serde(default)]
    pub embedding: Vec<f32>,
    /// Hash for deduplication (Zig SIMD)
    #[serde(default)]
    pub content_hash: String,
    /// Quality score (0.0 - 1.0)
    #[serde(default)]
    pub quality_score: f32,
    /// Processing metadata
    #[serde(default)]
    pub processing_info: ProcessingInfo,
}

/// Metadata about how the datapoint was processed
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct ProcessingInfo {
    /// Which processors were used
    pub used_processors: Vec<String>,
    /// Processing time in ms
    pub processing_time_ms: u64,
    /// Whether Go parallel processing was used
    pub go_parallel: bool,
    /// Whether Zig SIMD hashing was used
    pub zig_simd: bool,
    /// Whether Nim HTML parsing was used
    pub nim_parsing: bool,
    /// Whether JAX vectorization was used
    pub jax_embedding: bool,
    /// Whether Chapel AI optimization was used
    pub chapel_ai: bool,
}

